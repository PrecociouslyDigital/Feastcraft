"""`uv run python -m smithy`, and `install --instance <dir>`.

Reads the datapack export and `smithy.toml`, then writes the smithy datapack:
the disabled tag, one conversion per retired item, and `forge:false` overrides
plus rewrites for the recipes and advancements that name them.
"""

from __future__ import annotations

import argparse
import json
import shutil
import tomllib
from pathlib import Path
from typing import Any

import packexport

from . import export, tiers

HERE = Path(__file__).resolve().parent.parent
DATAPACK = HERE / "datapack"
EXPORT = HERE.parent.parent / "build" / "datapack-export"
CONFIG = HERE / "smithy.toml"
INSTALLED_AS = Path("config/openloader/data/feastcraft_smithy")

Json = dict[str, Any]

FALSE = {"conditions": [{"type": "forge:false"}]}

# Tinkers recipes that melt or cast a disabled item are how it becomes ingots, so they stay.
TINKERS_PREFIX = "tconstruct:"


def tool_definitions(export_dir: Path) -> dict[str, Any]:
    return {
        f"tconstruct:{file.with_suffix('').name}": json.loads(file.read_text())
        for file in (export_dir / "data" / "tconstruct" / "tinkering" / "tool_definitions").glob("*.json")
    }


def curate() -> tuple[dict[str, Any], dict[str, str]]:
    """The smithy.toml tables: a conversion per retired item, and what is kept."""
    raw = tomllib.loads(CONFIG.read_text())
    return raw.get("convert", {}), raw.get("keep", {})


def draft(export_dir: Path) -> None:
    """Emit a smithy.toml draft, one convert entry per tool, weapon or armor."""
    pack = packexport.load(export_dir)
    definitions = tool_definitions(export_dir)
    lines = ["# Generated by `uv run python -m smithy draft`, then curated by hand.", ""]
    convert: list[str] = []
    keep: list[str] = []
    for item, tags in sorted(export.tagged_items(pack).items()):
        made = tiers.conversion(item, tags, definitions)
        if made is None:
            keep.append(f'# "{item}" = ""  # no material for this tier')
            continue
        convert.append(f'[convert."{item}"]')
        convert.append(f'tool = "{made["tool"]}"')
        convert.append(f'materials = {json.dumps(made["materials"])}')
        convert.append(f'modifiers = {json.dumps(made["modifiers"])}')
        convert.append("")
    lines += convert + ["[keep]", *keep]
    CONFIG.write_text("\n".join(lines) + "\n")
    print(f"{len(convert)} convert, {len(keep)} without a material, into {CONFIG.name}")


def rewrite(recipe: Json, replacements: dict[str, str]) -> bool:
    """Swap every disabled item a recipe consumes for its Tinkers stand-in."""
    changed = False
    for container, item in list(export.recipe_items(recipe)):
        if item in replacements:
            container["item"] = replacements[item]
            changed = True
    return changed


def build(export_dir: Path) -> None:
    """Write datapack/, failing when a tagged item is neither kept nor converted."""
    pack = packexport.load(export_dir)
    tagged = export.tagged_items(pack)
    converts, keeps = curate()
    problems = [item for item in tagged if item not in converts and item not in keeps]
    if problems:
        for item in sorted(problems)[:20]:
            print(f"unlisted: {item} ({', '.join(sorted(tagged[item]))})")
        raise SystemExit(f"{len(problems)} tagged items are not in {CONFIG.name}")
    unknown = [item for item in converts if item not in tagged]
    if unknown:
        for item in sorted(unknown)[:20]:
            print(f"not tagged: {item}")
        raise SystemExit(f"{len(unknown)} converted items no tag names")

    recipes_dir = DATAPACK / "data"
    shutil.rmtree(recipes_dir, ignore_errors=True)
    conversions_dir = DATAPACK / "data" / "feastcraft_smithy" / "smithy" / "conversions"
    for item, made in sorted(converts.items()):
        namespace, _, name = item.partition(":")
        target = conversions_dir / namespace / f"{name}.json"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(made, indent=2) + "\n")
    disabled = DATAPACK / "data" / "feastcraft_smithy" / "tags" / "items" / "disabled.json"
    disabled.parent.mkdir(parents=True, exist_ok=True)
    disabled.write_text(json.dumps({"replace": False, "values": sorted(converts)}, indent=2) + "\n")

    replacements = {item: made["tool"] for item, made in converts.items()}
    disabled_results = {recipe.id for recipe in pack.recipes if recipe.result in replacements}
    skipped = set()
    for id, recipe in export.recipes(export_dir):
        namespace, _, path = id.partition(":")
        target = recipes_dir / namespace / "recipes" / f"{path}.json"
        if id in disabled_results:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(json.dumps(FALSE, indent=2) + "\n")
            continue
        if recipe.get("type", "").startswith(TINKERS_PREFIX):
            continue
        if rewrite(recipe, replacements):
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(json.dumps(recipe, indent=2) + "\n")
        else:
            skipped.add(id)
    for id, advancement in export.advancements(export_dir):
        namespace, _, path = id.partition(":")
        if rewrite(advancement, replacements):
            target = recipes_dir / namespace / "advancements" / f"{path}.json"
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(json.dumps(advancement, indent=2) + "\n")

    print(f"{len(converts)} conversions, {len(disabled_results)} recipes overridden, "
          f"{sum(1 for _ in (recipes_dir / 'feastcraft_smithy' / 'smithy' / 'conversions').rglob('*.json'))} written")


def install(instance: Path) -> None:
    target = instance / INSTALLED_AS
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(DATAPACK, target)
    print(f"installed to {target}")


def main() -> None:
    parser = argparse.ArgumentParser(prog="smithy")
    parser.add_argument("--export", type=Path, default=EXPORT)
    commands = parser.add_subparsers(dest="command")
    commands.add_parser("draft", help="emit a smithy.toml draft from the export")
    install_command = commands.add_parser("install", help="copy the datapack into an instance's Open Loader folder")
    install_command.add_argument("--instance", type=Path, required=True)
    args = parser.parse_args()

    if args.command == "draft":
        draft(args.export)
    elif args.command == "install":
        install(args.instance)
    else:
        build(args.export)


if __name__ == "__main__":
    main()
